function render(key) {
  const data = information[key];

  document.getElementById("drawerTitle").textContent = data.title;
  document.getElementById("drawerImage").src = data.image;

  document.getElementById("drawerGrid").innerHTML = data.items
    .map(
      (item) => `
<div class="drawer-item">
  <strong>${item[0]}</strong>
  <span>${item[1]}</span>
</div>
`,
    )
    .join("");
}

function select(key) {
  render(key);

  document.querySelectorAll(".concept").forEach((node) => {
    node.style.opacity = ".28";
  });

  document.getElementById(key).style.opacity = "1";

  document.querySelectorAll(".connections path").forEach((line) => {
    line.classList.remove("active");
  });

  const line = document.getElementById("line-" + key);

  if (line) {
    line.classList.add("active");
  }

  openDrawer();
}

function openDrawer() {
  document.getElementById("drawerOverlay").classList.add("open");
  document.getElementById("sideDrawer").classList.add("open");
}

function closeDrawer() {
  document.getElementById("drawerOverlay").classList.remove("open");
  document.getElementById("sideDrawer").classList.remove("open");
}

function focusNode(key, button) {
  document.querySelectorAll(".controls button").forEach((btn) => {
    btn.classList.remove("active");
  });

  button.classList.add("active");

  select(key);
}

function showAll(button) {
  document.querySelectorAll(".controls button").forEach((btn) => {
    btn.classList.remove("active");
  });

  button.classList.add("active");

  document.querySelectorAll(".concept").forEach((node) => {
    node.style.opacity = "1";
  });

  document.querySelectorAll(".connections path").forEach((line) => {
    line.classList.remove("active");
  });

  closeDrawer();
}
